/**
 * Получить пресет по id (1-5)
 * @param {number} id
 * @returns {Object} конфиг пресета
 */
export function getPreset(id) {
  const preset = PRESETS.find(p => p.id === id);
  if (!preset) throw new Error(`[presets.js] Пресет с id=${id} не найден`);
  // Возвращаем копию чтобы пользователь не мог изменить оригинал
  return { ...preset };
}
